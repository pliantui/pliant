import { execFileSync } from "node:child_process"
import { readdirSync, readFileSync, writeFileSync } from "node:fs"
import { fileURLToPath } from "node:url"
import { wrapLanguageModel } from "ai"
import { MockLanguageModelV4 } from "ai/test"
import * as z from "zod"

import {
  askRequestSchema,
  askResponseSchema,
  createPliantHandler,
} from "@pliantui/server"
import { recordingMiddleware } from "@pliantui/server/recordings"

// Replays every demo ask from the committed recordings and writes the
// answers to `lib/replay/recorded-answers.generated.ts`: `pnpm --filter www
// replays:build`. The site answers asks from that module in the browser, so
// replaying needs no server and no model.

const recordingsDirectory = new URL("../recordings/", import.meta.url)
const output = fileURLToPath(
  new URL("../lib/replay/recorded-answers.generated.ts", import.meta.url)
)

const demoSchema = z.strictObject({
  surface: z.string(),
  targets: z.array(
    z.strictObject({
      target: z.string(),
      context: z.unknown(),
      prompts: z.array(z.string()),
    })
  ),
})

// The shape of `lib/replay/recorded-answer.ts`, which the site reads.
interface RecordedAnswer {
  target: string
  prompt: string
  answer:
    | { status: "ok"; ops: unknown[]; basis: unknown; explain: string[] }
    | { status: "clarify"; question: string }
}

export async function replayDemoAsks(): Promise<RecordedAnswer[]> {
  const demo = demoSchema.parse(
    JSON.parse(readFileSync(new URL("demo-asks.json", import.meta.url), "utf8"))
  )
  const recordings: unknown[] = readdirSync(recordingsDirectory)
    .filter((file) => file.endsWith(".json"))
    .sort()
    .map((file): unknown =>
      JSON.parse(readFileSync(new URL(file, recordingsDirectory), "utf8"))
    )
  const model = wrapLanguageModel({
    // The stand-in only names the model the recordings were made with;
    // replay answers every call before it's reached.
    model: new MockLanguageModelV4({
      provider: "anthropic.messages",
      modelId: "claude-haiku-5-5",
    }),
    middleware: recordingMiddleware({ mode: "replay", recordings }),
  })
  const errors: unknown[] = []
  const handler = createPliantHandler({
    model,
    getUser: () => "anonymous",
    onError: (error) => {
      errors.push(error)
    },
  })

  const answers: RecordedAnswer[] = []
  for (const { target, context, prompts } of demo.targets) {
    for (const prompt of prompts) {
      const ask = askRequestSchema.parse({
        surface: demo.surface,
        target,
        prompt,
        context,
      })
      const response = await handler(
        new Request("http://localhost/", {
          method: "POST",
          headers: { "content-type": "application/json" },
          body: JSON.stringify(ask),
        })
      )
      const body = askResponseSchema.parse(await response.json())
      if (body.status === "ok") {
        const { ops, basis } = body.overlay
        answers.push({
          target,
          prompt,
          answer: { status: "ok", ops, basis, explain: body.explain },
        })
      } else if (body.status === "clarify") {
        answers.push({ target, prompt, answer: body })
      } else {
        throw new Error(
          `"${target}: ${prompt}" has no usable recording: ${JSON.stringify(body)}`,
          { cause: errors[0] }
        )
      }
    }
  }
  return answers
}

if (process.argv[1] === fileURLToPath(import.meta.url)) {
  const answers = await replayDemoAsks()
  writeFileSync(
    output,
    [
      "// Generated by `pnpm --filter www replays:build`. Don't edit it by hand.\n\n",
      'import type { RecordedAnswer } from "./recorded-answer"\n\n',
      `export const recordedAnswers: RecordedAnswer[] = ${JSON.stringify(answers)}\n`,
    ].join("")
  )
  execFileSync("pnpm", [
    "--workspace-root",
    "exec",
    "prettier",
    "--write",
    output,
  ])
  console.log(`Wrote ${String(answers.length)} recorded answers.`)
}
